#code for finding area of circle and rectangle in python
pi = 3.14
r = float(input("enter the radius of circle: "))
circlearea = pi * r * r
print("Area of circle:", circlearea)

a = float(input("pls enter the length of Rectangle: "))
b = float(input("please enter the breadth of rectangle: "))
rectanglearea = a * b
print("Area of rectangle:", rectanglearea)